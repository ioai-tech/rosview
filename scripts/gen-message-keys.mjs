/**
 * Writes src/shared/intl/messageKeys.generated.ts: the union of every English message id.
 * The published d.ts must not import the JSON catalogs (they are not shipped), so the union
 * lives in a plain .ts file that api-extractor can inline.
 *
 *   node scripts/gen-message-keys.mjs          write the file
 *   node scripts/gen-message-keys.mjs --check  exit 1 when the file is out of date
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const dir = path.join(root, 'src/shared/intl/messages/en');
const keys = fs
  .readdirSync(dir)
  .filter((f) => f.endsWith('.json'))
  .flatMap((f) => Object.keys(JSON.parse(fs.readFileSync(path.join(dir, f), 'utf8'))))
  .sort();
const out =
  '// Generated by scripts/gen-message-keys.mjs from messages/en/*.json. Do not edit.\n' +
  'export type RosViewMessageKey =\n' +
  keys.map((k) => `  | ${JSON.stringify(k)}`).join('\n') +
  ';\n';
const target = path.join(root, 'src/shared/intl/messageKeys.generated.ts');
if (process.argv.includes('--check')) {
  const current = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : '';
  if (current !== out) {
    console.error('messageKeys.generated.ts is out of date: run node scripts/gen-message-keys.mjs');
    process.exit(1);
  }
  console.log(`messageKeys.generated.ts: ok (${keys.length} keys)`);
} else {
  fs.writeFileSync(target, out);
  console.log(`wrote ${target} (${keys.length} keys)`);
}
